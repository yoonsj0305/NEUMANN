"""Independent Z3 proof of original SyGuS Bool invertibility-condition ASTs.

Uses the ORIGINAL official quantifier-expanded case predicates and freshly
compiles candidate Boolean ASTs to SMT-LIB. It NEVER calls the Q3 custom
4-bit evaluator, existential compiler, source-derived cover solver, or target
truth tables. Proves UNSAT of the original constraint's negation over all
256 s,t assignments. Cross-checks every claimed solution, not only winners.
"""
import hashlib,json,pathlib,re,time,urllib.request
import z3

UPSTREAM="13c8deb68a873635879c9a69bc78caebd340f646"
ROOT=f"https://raw.githubusercontent.com/SyGuS-Org/benchmarks/{UPSTREAM}/comp/2019/General_Track/bv-invertibility-conditions/"
LEDGERS=[
 ("prior_first/Q3_BOOLEAN_INVARIANT_FRESH_FIRST.json","rows",
    ("strong_cold","causal_invariant")),
 ("prior_second/Q3_CAUSAL_DUAL_FRESH_ORIGINAL_FIRST.json","records",
    ("prior_source_or","autogenerated_dual","source_guided_residual","strong_semantic_classical")),
 ("prior_third/Q3_CAUSAL_DUAL_FRESH_ORIGINAL_FIRST.json","records",
    ("prior_source_or","autogenerated_dual","source_guided_residual","strong_semantic_classical"))]

def tokenize(s):
    s=re.sub(r";[^\n]*","",s)
    return re.findall(r"\(|\)|[^\s()]+",s)

def parse(s):
    tokens=tokenize(s);stack=[];top=[]
    for token in tokens:
        if token=="(":
            frame=[]
            (stack[-1] if stack else top).append(frame)
            stack.append(frame)
        elif token==")":
            if not stack:raise ValueError("UNBALANCED_CLOSE")
            stack.pop()
        else:
            if not stack:raise ValueError("OUTSIDE_FORM")
            stack[-1].append(token)
    if stack:raise ValueError("UNCLOSED_FORM")
    return top

def smt(node):
    if not isinstance(node,list):return str(node)
    if len(node)==2 and node[0]=="BitVec":
        return "(_ BitVec "+str(node[1])+")"
    return "("+" ".join(smt(z) for z in node)+")"

def ast_smt(node):
    if not isinstance(node,list) or not node:
        raise ValueError("BAD_GENERATED_PROGRAM")
    op=node[0]
    if op in ("s","t") and len(node)==1:return op
    if op=="lit" and len(node)==2 and type(node[1]) is int and 0<=node[1]<=15:
        return "#x"+format(node[1],"x")
    if op=="const" and len(node)==2 and type(node[1]) is bool:
        return "true" if node[1] else "false"
    if op in ("bvneg","bvnot") and len(node)==2:
        return "("+op+" "+ast_smt(node[1])+")"
    if op in ("bvadd","bvsub","bvand","bvor","bvshl","bvlshr",
              "=","bvult","bvslt","bvuge","bvsge",
              "and","or") and len(node)==3:
        return "("+op+" "+ast_smt(node[1])+" "+ast_smt(node[2])+")"
    if op=="not" and len(node)==2:
        return "(not "+ast_smt(node[1])+")"
    raise ValueError("OUT_OF_SYNTAX_CANDIDATE_"+str(op))

def build(original,program):
    forms=parse(original)
    synth=[x for x in forms if x and x[0]=="synth-fun"]
    if len(synth)!=1 or synth[0][1]!="SC" or synth[0][3]!="Bool":
        raise ValueError("UNEXPECTED_PREDICATE_SCHEMA")
    out=["(set-logic QF_BV)",
        "(define-fun SC ((s (_ BitVec 4)) (t (_ BitVec 4))) Bool "+ast_smt(program)+")"]
    constraints=0
    for f in forms:
        if not f:continue
        tag=f[0]
        if tag in ("set-logic","check-synth","synth-fun"):continue
        if tag=="declare-var":
            if len(f)!=3:raise ValueError("BAD_DECL")
            out.append("(declare-const "+f[1]+" "+smt(f[2])+")")
        elif tag=="define-fun":
            out.append(smt(f))
        elif tag=="constraint":
            if len(f)!=2:raise ValueError("BAD_CONSTRAINT")
            constraints+=1
            out.append("(assert (not "+smt(f[1])+"))")
        else:raise ValueError("UNSUPPORTED_TOPLEVEL")
    if constraints!=1:raise ValueError("WRONG_CONSTRAINT_COUNT")
    return "\n".join(out)

def prove(smt_text):
    t=time.perf_counter_ns()
    solver=z3.Solver()
    solver.set(timeout=8000)
    solver.from_string(smt_text)
    status=solver.check()
    elapsed=(time.perf_counter_ns()-t)/1e6
    if status==z3.unsat:return "INDEPENDENT_Z3_UNSAT",round(elapsed,5),None
    if status==z3.sat:return "COUNTEREXAMPLE_Z3_SAT",round(elapsed,5),str(solver.model())[:300]
    return "VERIFIER_UNKNOWN",round(elapsed,5),str(solver.reason_unknown())

cache={}
def official(name):
    if name not in cache:
        with urllib.request.urlopen(ROOT+name,timeout=25) as h:
            raw=h.read(150001)
        if len(raw)>150000:raise ValueError("ORIGINAL_TOO_LARGE")
        cache[name]=raw.decode()
    return cache[name]

def audit():
    rows=[];cached={}
    for filename,section,arms in LEDGERS:
        ledger=json.loads(pathlib.Path(filename).read_text())
        prev=ledger.get(section,[])
        for rec in prev:
            if "error" in rec:continue
            name=rec["id"] if "id" in rec else rec["name"]
            for arm in arms:
                item=rec.get("arms",{}).get(arm) if "arms" in rec else rec.get(arm)
                if not item:continue
                claimed=item.get("exact_256",item.get("proved",False))
                ast=item.get("program_ast",item.get("ast"))
                if ast is None:continue
                key=(name,json.dumps(ast,sort_keys=True))
                if key not in cached:
                    try:
                        orig=official(name)
                        sha=hashlib.sha256(orig.encode()).hexdigest()
                        if rec.get("original_sha256")!=sha:
                            raise ValueError("ORIGINAL_SOURCE_HASH_CHANGED")
                        status,ms,cex=prove(build(orig,ast))
                        cached[key]={"status":status,"verify_ms":ms,
                                     "counterexample":cex}
                    except Exception as e:
                        cached[key]={"status":"VERIFIER_ERROR",
                                     "error":type(e).__name__+": "+str(e)[:190]}
                rows.append({"original_file":name,"prior_ledger":filename,
                      "arm":arm,"claimed_success":bool(claimed),
                      "program_ast":ast,**cached[key]})
    results={"schema":"neumann.q3.bool-existence-independent-z3-cross-check.v1",
             "independent_verifier":"Z3 "+z3.get_version_string(),
             "upstream_commit":UPSTREAM,
             "rows":rows,
             "summary":{
               "submitted_records":len(rows),
               "distinct_problem_ast_pairs":len(cached),
               "distinct_original_tasks":len({x["original_file"] for x in rows}),
               "independent_unsat_proofs":sum(x["status"]=="INDEPENDENT_Z3_UNSAT" for x in rows),
               "sat_counterexamples":sum(x["status"]=="COUNTEREXAMPLE_Z3_SAT" for x in rows),
               "verifier_errors":sum(x["status"] in ("VERIFIER_ERROR","VERIFIER_UNKNOWN") for x in rows),
               "claimed_success_not_proved":sum(x["claimed_success"] and x["status"]!="INDEPENDENT_Z3_UNSAT" for x in rows)}}
    pathlib.Path("Q3_BOOLEAN_INDEPENDENT_Z3_PROOFS.json").write_text(json.dumps(results,indent=2))
    print(json.dumps(results["summary"],indent=2))
    if results["summary"]["claimed_success_not_proved"]:
        raise AssertionError("FORMAL_SOLVER_PROOF_FALSE_POSITIVE")
    return results

if __name__=="__main__":audit()
