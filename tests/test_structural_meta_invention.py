"""Core behavior checks, not benchmark success claims.

Any new program is accepted only when the caller's original semantics agree.
The SAME structural miner discovers two different kinds of recursion without
having the words fold/scan or a catalog of domain-specific control graphs.
"""
from __future__ import annotations

from itertools import product

from neumann1.structural_meta_invention import (
    CertifiedProgram, StructuralMetaInventor, _size)
from neumann1.engine import NeumannEngine


def arg(i):
    return ("arg", i)


def ev(tree, values):
    op = tree[0]
    if op == "arg":
        return values[tree[1]]
    if op == "lit":
        return tree[1]
    xs = [ev(x, values) for x in tree[1:]]
    return {
        "lt": lambda a,b: a < b,
        "gt": lambda a,b: a > b,
        "add": lambda a,b: a + b,
        "ite": lambda p,t,f: t if p else f,
    }[op](*xs)


def mx2():
    a,b = arg(0),arg(1)
    return ("ite", ("lt",a,b),b,a)


def mx3():
    prev=mx2()
    b=arg(2)
    return ("ite",("lt",prev,b),b,prev)


def pair(i):
    return ("add",arg(i),arg(i+1))


def scan2():
    p=pair(0)
    return ("ite",("gt",p,("lit",5)),p,("lit",0))


def scan3():
    p=pair(0)
    q=pair(1)
    return ("ite",("gt",p,("lit",5)),p,
             ("ite",("gt",q,("lit",5)),q,("lit",0)))


def original_max(expr, n):
    return all(ev(expr, row)==max(row)
               for row in product((-3,0,2,7),repeat=n))


def original_first_hit(expr, n, threshold):
    for row in product((-1,0,2,9,18),repeat=n):
        expected=next((row[i]+row[i+1] for i in range(n-1)
                       if row[i]+row[i+1]>threshold),0)
        if ev(expr,row)!=expected:
            return False
    return True


def test_live_engine_mines_two_distinct_methods_and_self_updates():
    engine=NeumannEngine(None, [], None)
    s2=CertifiedProgram("generic.int.selector",2,mx2(),certificate="max2-original")
    s3=CertifiedProgram("generic.int.selector",3,mx3(),certificate="max3-original")
    assert engine.observe_program(s2,verify=lambda p:original_max(p.expr,p.arity))==[]
    discovered=engine.observe_program(s3,verify=lambda p:original_max(p.expr,p.arity))
    assert len(discovered)==1
    assert discovered[0].direction=="append"
    assert not any("fold" in str(p.context) or "scan" in str(p.context)
                   for p in discovered)
    out=engine.invent_program("generic.int.selector",4,
                verify=lambda tree: original_max(tree,4))
    assert out["verified"] and out["program"]
    assert engine.meta_inventor.methods[out["method_id"]].successes==1
    assert out["new_method_ids"]  # Adjacent verified source grows search language again.
    next_result=engine.invent_program("generic.int.selector",5,
                verify=lambda tree: original_max(tree,5))
    assert next_result and next_result["verified"]

    # With a shared DAG, recurrence of the previous expression does NOT
    # cause exponential memory growth.
    result=engine.invent_program("generic.int.selector",11,
                                verify=lambda tree: ev(tree,tuple(range(11)))==10)
    assert result and _size(result["program"]) < 100


def test_autogenerated_prepend_method_and_unseen_numeric_parameter():
    inventor=StructuralMetaInventor()
    s2=CertifiedProgram("integer.priority",2,scan2(),certificate="scan2-original",params=(5,))
    s3=CertifiedProgram("integer.priority",3,scan3(),certificate="scan3-original",params=(5,))
    # Simulated original semantics; the real production checker is injected.
    inventor.observe(s2,verify=lambda s:original_first_hit(s.expr,s.arity,5))
    derived=inventor.observe(s3,verify=lambda s:original_first_hit(s.expr,s.arity,5))
    assert len(derived)==1 and derived[0].direction=="prepend"
    assert derived[0].parameters==1
    solution=inventor.solve("integer.priority",4,params=(15,),
                  verify=lambda tree:original_first_hit(tree,4,15),
                  promote=True)
    assert solution is not None and solution["verified"]
    assert solution["new_method_ids"]


def test_failed_or_unverified_inventions_cannot_pollute_runtime():
    inventor=StructuralMetaInventor()
    lo=CertifiedProgram("f",2,mx2(),certificate="original-2")
    hi=CertifiedProgram("f",3,mx3(),certificate="original-3")
    assert inventor.learn(lo,hi,verify=lambda p:False)==[]
    assert not inventor.methods
    assert inventor.learn(lo,hi,verify=lambda p:True)
    assert inventor.solve("f",4,verify=None) is None
    assert inventor.solve("f",4,verify=lambda p:False) is None
    assert all(m.successes==0 for m in inventor.methods.values())
    assert inventor.solve("f",4,verify=lambda p:original_max(p,4))


def test_input_rejection_and_budget():
    inventor=StructuralMetaInventor(max_arity=6)
    lo=CertifiedProgram("f",2,mx2(),certificate="c2")
    hi=CertifiedProgram("f",3,mx3(),certificate="c3")
    try:
        CertifiedProgram("f",2,("arg",2),certificate="bad")
        assert False, "must fail"
    except ValueError:
        pass
    inventor.learn(lo,hi,verify=lambda p:True)
    try:
        list(inventor.candidates("f",7))
        assert False, "cap must fail"
    except ValueError:
        pass

def test_durable_method_inventory_reloads_without_relearning():
    from neumann1 import RegistryEngine
    creator=NeumannEngine(None,[],None)
    creator.observe_program(
        CertifiedProgram("persistence.max",2,mx2(),certificate="source2"),
        verify=lambda p:original_max(p.expr,p.arity))
    creator.observe_program(
        CertifiedProgram("persistence.max",3,mx3(),certificate="source3"),
        verify=lambda p:original_max(p.expr,p.arity))
    snapshot=creator.meta_inventor.checkpoint()
    assert snapshot["methods"]
    restored=StructuralMetaInventor.from_checkpoint(snapshot)
    # Check the SECOND official production routing engine can use the same
    # checkpoint without source examples or hardcoded templates.
    engine=RegistryEngine(None,None,meta_inventor=restored)
    proposal=engine.invent_program(
        "persistence.max",4,
        verify=lambda p:original_max(p,4))
    assert proposal and proposal["verified"]
    damaged=dict(snapshot,sha256="0"*64)
    try:
        StructuralMetaInventor.from_checkpoint(damaged)
        assert False, "checksum must reject accidental drift"
    except ValueError:
        pass


def test_invalid_truthy_verifier_cannot_certify_a_method():
    core=StructuralMetaInventor()
    src2=CertifiedProgram("not-proved",2,mx2(),certificate="untrusted2")
    src3=CertifiedProgram("not-proved",3,mx3(),certificate="untrusted3")
    assert core.learn(src2,src3,verify=lambda x:"false")==[]
    assert not core.methods
    core.learn(src2,src3,verify=lambda x:True)
    assert core.solve("not-proved",4,verify=lambda x:"false") is None
    assert all(m.successes==0 for m in core.methods.values())


def test_discovers_interior_insert_alignment_from_program_structure():
    """The old append/prepend-only engine cannot represent arg insertion at 1."""
    s2=mx2()
    a0,a1,a2=arg(0),arg(1),arg(2)
    old_in_new=("ite",("lt",a0,a2),a2,a0)
    s3=("ite",("lt",old_in_new,a1),a1,old_in_new)
    miner=StructuralMetaInventor(max_arity=12)
    source2=CertifiedProgram("unseen.middle.max",2,s2,certificate="2-certified")
    source3=CertifiedProgram("unseen.middle.max",3,s3,certificate="3-certified")
    assert miner.observe(source2,verify=lambda p:original_max(p.expr,p.arity))==[]
    methods=miner.observe(source3,verify=lambda p:original_max(p.expr,p.arity))
    assert methods and any(m.direction=="insert" and m.insertion_index==1
                           and m.reverse is False for m in methods)
    candidate=miner.solve("unseen.middle.max",4,
                          verify=lambda ast:original_max(ast,4),promote=True)
    assert candidate and candidate["verified"]
    assert miner.solve("unseen.middle.max",5,
                       verify=lambda ast:original_max(ast,5))
    snapshot=miner.checkpoint()
    restored=StructuralMetaInventor.from_checkpoint(snapshot)
    assert any(x.direction=="insert" and x.insertion_index==1
               for x in restored.methods.values())
    assert restored.solve("unseen.middle.max",6,
                          verify=lambda ast:original_max(ast,6))


def test_discovers_reversed_variable_alignment_by_source_only():
    """A reverse-and-insert transformation is inferred without source hints."""
    s2=mx2()
    a0,a1,a2=arg(0),arg(1),arg(2)
    reversed_old=("ite",("lt",a2,a0),a0,a2)
    s3=("ite",("lt",reversed_old,a1),a1,reversed_old)
    miner=StructuralMetaInventor(max_arity=7)
    src2=CertifiedProgram("reverse.max",2,s2,certificate="2")
    src3=CertifiedProgram("reverse.max",3,s3,certificate="3")
    miner.observe(src2,verify=lambda p:original_max(p.expr,p.arity))
    learned=miner.observe(src3,verify=lambda p:original_max(p.expr,p.arity))
    assert learned
    assert any(x.direction=="permuted_insert" and x.reverse and
               x.insertion_index==1 for x in learned)
    assert miner.solve("reverse.max",4,
                       verify=lambda tree:original_max(tree,4))
    assert miner.solve("reverse.max",5,
                       verify=lambda tree:original_max(tree,5))


def test_new_alignment_does_not_forge_correctness_on_negative_target():
    s2=CertifiedProgram("counterexample.family",2,mx2(),certificate="source2")
    a0,a1,a2=arg(0),arg(1),arg(2)
    old=("ite",("lt",a0,a2),a2,a0)
    s3=CertifiedProgram("counterexample.family",3,
                        ("ite",("lt",old,a1),a1,old),certificate="source3")
    miner=StructuralMetaInventor()
    miner.learn(s2,s3,verify=lambda p:True)
    # A valid structural continuation need not satisfy a different target's
    # mathematical specification. Require external verifier approval.
    assert miner.solve("counterexample.family",4,
                       verify=lambda tree:all(ev(tree,row)==min(row)
                           for row in product((-1,0,3),repeat=4))) is None
    assert all(x.successes==0 for x in miner.methods.values())


def test_method_search_continues_after_checkpoint_reload():
    """Fix real runtime limitation: methods-only state had lost source n+1."""
    from neumann1.structural_meta_invention import _hash
    a0,a1,a2=arg(0),arg(1),arg(2)
    old=("ite",("lt",a0,a2),a2,a0)
    s3=("ite",("lt",old,a1),a1,old)
    miner=StructuralMetaInventor()
    miner.observe(CertifiedProgram("long.lived",2,mx2(),certificate="s2"),
                  verify=lambda p:original_max(p.expr,p.arity))
    miner.observe(CertifiedProgram("long.lived",3,s3,certificate="s3"),
                  verify=lambda p:original_max(p.expr,p.arity))
    stored=miner.checkpoint()
    assert stored["schema"].endswith("v2")
    assert len(stored["observations"])==2
    reloaded=StructuralMetaInventor.from_checkpoint(stored)
    answer=reloaded.solve("long.lived",4,
                          verify=lambda p:original_max(p,4),
                          promote=True)
    assert answer and answer["verified"]
    assert answer["new_method_ids"]  # New method induced using restored n3.
    assert reloaded.solve("long.lived",5,
                          verify=lambda p:original_max(p,5))
    # Old snapshots remain readable, but correctly cannot claim persisted
    # source observations that the old format never serialized.
    old_version={k:v for k,v in stored.items() if k not in ("observations","sha256")}
    old_version["schema"]="neumann.structural-meta-methods.v1"
    old_version["sha256"]=_hash(old_version)
    previous=StructuralMetaInventor.from_checkpoint(old_version)
    assert previous.methods and not previous.observations
    assert previous.solve("long.lived",4,
                          verify=lambda p:original_max(p,4))


def test_checkpoint_rejects_corrupted_source_program_state():
    from neumann1.structural_meta_invention import _hash
    m=StructuralMetaInventor()
    m.observe(CertifiedProgram("x",2,mx2(),certificate="source"),
              verify=lambda _:True)
    state=m.checkpoint()
    state["observations"][0]["expr"]=["arg",3]  # nonexistent arity
    state["sha256"]=_hash({k:v for k,v in state.items() if k!="sha256"})
    try:
        StructuralMetaInventor.from_checkpoint(state)
        assert False, "malformed restored program must be rejected"
    except ValueError:
        pass
