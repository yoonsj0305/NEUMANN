"""Q3: actual learned discovery controller, counterexample-driven rewrite, Q6.

The 300 graded inputs are strictly disjoint from each task's source probes.
All source task families are generated by a scorer, not routed by the learner.
"""
import pytest
from neumann1.discovery_policy_core import (
    DiscoveryMethodLearner,DiscoveryProcedureExecutor,DiscoveryStage,
    InferredDiscoveryMethod,PolicyEvidenceError,
    revise_discovery_method,
)
from research.q3.q3_self_revising_discovery_first import (
    bits,random_anfs,graph_triangles_permuted,hidden_grade_inputs,
    training_tasks,counterexample_feedback,execute_first,
)


def test_learned_method_is_a_new_conditional_ast_not_a_fixed_solver():
    learner=DiscoveryMethodLearner(verifier_counts=(8,16,32))
    found=learner.learn(training_tasks())
    assert len(found.trace)==12
    assert found.training_task_count==24
    assert found.policy.steps==tuple(
        DiscoveryStage(d,8) for d in (1,2,3))
    assert len(found.policy.steps)>1
    assert found.policy.ast[0]=="IF_SOURCE_COUNTEREXAMPLE"
    assert found.meta_training_queries==8207


def test_meta_training_recovers_after_a_real_discovery_failure():
    original=training_tasks()
    learner=DiscoveryMethodLearner(verifier_counts=(8,16,32))
    first=learner.learn(original)
    revision=revise_discovery_method(
        learner,first,original,counterexample_feedback())
    assert revision.previous_digest!=revision.revised_digest
    assert revision.original_feedback_errors==59
    assert revision.repaired_feedback_errors==0
    assert revision.revised.policy.steps==tuple(
        DiscoveryStage(d,16) for d in (1,2,3))
    assert revision.revised.meta_training_queries==8569
    assert revision.visible_meta_source_cost==8716


def test_known_classical_solution_means_zero_new_invention():
    classical=lambda x:x[1]^x[5]
    counted=[]
    def source(x):
        counted.append(x)
        return classical(x)
    method=InferredDiscoveryMethod(tuple(
        DiscoveryStage(d,16) for d in (1,2,3)))
    run=DiscoveryProcedureExecutor().run(
        method,source,width=10,seed=100,
        classical_solvers=(classical,),classical_probe_checks=32)
    assert run.status=="CLASSICAL_SOURCE_VERIFIED"
    assert run.stages_reached==0
    assert run.source_queries==32
    assert len(counted)==32
    assert all(run.apply(bits(i,10))==classical(bits(i,10))
               for i in range(1024))


def test_failure_counterexample_changes_the_discovery_process():
    source=random_anfs(31552,12,3)
    method=InferredDiscoveryMethod(tuple(
        DiscoveryStage(d,64) for d in (1,2,3)))
    run=DiscoveryProcedureExecutor().run(
        method,source,width=12,seed=18)
    assert run.status=="SOURCE_VERIFIED"
    assert run.stages_reached==3
    assert run.counterexample_count>=1
    assert any("COUNTEREXAMPLE" in x[1] for x in run.trace)
    assert all(run.apply(bits(i,12))==source(bits(i,12))
               for i in range(4096))


def test_target_scoring_inputs_are_rejected_as_source_queries():
    forbidden=hidden_grade_inputs(12,9981,128)
    sealed=set(forbidden)
    source=random_anfs(28100,12,2)
    def guarded(x):
        if x in sealed:
            raise AssertionError("no target gold ever allowed in source")
        return source(x)
    method=InferredDiscoveryMethod(tuple(
        DiscoveryStage(d,32) for d in (1,2,3)))
    run=DiscoveryProcedureExecutor().run(
        method,guarded,width=12,seed=44,
        forbidden_inputs=forbidden)
    assert run.status=="SOURCE_VERIFIED"
    assert all(run.apply(x)==source(x) for x in forbidden)


def test_resource_guard_and_invalid_degree_rewrite_fail_closed():
    method=InferredDiscoveryMethod((DiscoveryStage(3,16),))
    run=DiscoveryProcedureExecutor(max_queries=6).run(
        method,lambda x:sum(x)%2,width=12,seed=12)
    assert run.status=="ABSTAIN_QUERY_LIMIT"
    assert run.program is None
    with pytest.raises(PolicyEvidenceError):
        run.apply(bits(1,12))
    with pytest.raises(ValueError):
        DiscoveryProcedureExecutor().run(
            InferredDiscoveryMethod(
                (DiscoveryStage(2,16),DiscoveryStage(1,16))),
            lambda x:0,width=12,seed=1)


@pytest.mark.parametrize("engine_kind",["NeumannEngine","RegistryEngine"])
def test_live_neumann_engines_learn_revise_and_reuse_meta_policy(engine_kind):
    from neumann1 import NeumannEngine,RegistryEngine
    engine=(NeumannEngine(None,[],None) if engine_kind=="NeumannEngine"
            else RegistryEngine(None,None))
    initial=engine.meta_learn_discovery_method(
        training_tasks(),max_degree=3,
        verifier_counts=(8,16,32))
    revision=engine.meta_revise_discovery_method(
        counterexample_feedback())
    assert revision.revised_digest!=initial.digest
    oracle=graph_triangles_permuted(920019)
    target=hidden_grade_inputs(10,108019,128)
    run=engine.meta_execute_discovery_method(
        oracle,width=10,seed=12381,
        forbidden_inputs=target)
    assert run.status=="SOURCE_VERIFIED"
    assert all(run.apply(x)==oracle(x) for x in target)


