"""Q3: transfer SOURCE-certified algorithm fragments into NEW model programs.

This module never sees target gold, task descriptions, or reference code.
It reads previously generated executable programs and their independent
SOURCE certificates, extracts free-variable-safe subexpressions, and
recombines them with NEW independently proposed programs. Every newly
constructed program must exactly pass BOTH new train and disjoint SOURCE
checks in an isolated runtime before being promoted to target prediction.

This is data-derived compositional operator transfer, not the creation of
fundamental new machine instructions. Classical fragment substitution is
the human-coded mechanism; fragments themselves are generated by Q3 policy.
"""
from __future__ import annotations

import ast
import copy
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path

from .open_program_inventor import IsolatedPython,UnsafeProposal,validate_code


def _sha(s):
    return hashlib.sha256(s.encode()).hexdigest()


@dataclass(frozen=True)
class MemorizedOperator:
    origin_id: str
    code: str
    sha256: str
    source_pairs: tuple


class CertifiedFragmentLibrary:
    def __init__(self,records):
        self.records=tuple(records)
        self._verified=False
        self.fragments=()

    @classmethod
    def load(cls,path):
        blob=json.loads(Path(path).read_text())
        if blob.get("schema")!="NEUMANN.Q3.INDEPENDENT.SOURCE.MACROS.v1":
            raise ValueError("source library schema mismatch")
        records=[]
        for e in blob["records"]:
            code=validate_code(e["program"])
            if _sha(code)!=e["program_sha256"]:
                raise ValueError("tampered source-program SHA")
            pairs=tuple(tuple(p) for p in e["source_pairs"])
            if len(pairs)<2:
                raise ValueError("source operator not independently certified")
            records.append(MemorizedOperator(
                str(e["external_original_id"]),code,
                _sha(code),pairs))
        return cls(records)

    def certify(self,runner):
        fragments=[]
        for op in self.records:
            result=runner.evaluate(op.code,[a for a,b in op.source_pairs])
            if result.status!="EXECUTED" or list(result.outputs)!=[
                    b for a,b in op.source_pairs]:
                raise ValueError("old source program did not reproduce")
            tree=ast.parse(op.code)
            for node in ast.walk(tree):
                if not isinstance(node,(
                        ast.Call,ast.BinOp,ast.Subscript,ast.IfExp)):
                    continue
                # Only a closed operator with one free input variable may
                # be exported across semantics; never leak a local variable
                # from a loop, comprehension or helper into another program.
                bound={n.id for n in ast.walk(node)
                       if isinstance(n,ast.Name)}
                builtins={"len","range","set","list","tuple","dict",
                          "sorted","reversed","sum","min","max","abs",
                          "str","int","float","bool","enumerate","zip"}
                if bound-builtins!={"x"}:
                    continue
                if any(isinstance(z,(
                    ast.NamedExpr,ast.Yield,ast.Await,ast.Lambda))
                       for z in ast.walk(node)):
                    continue
                candidate=ast.unparse(node)
                if candidate!="x" and candidate not in fragments:
                    fragments.append(candidate)
        self.fragments=tuple(fragments[:24])
        self._verified=True
        return self


class _ReplaceAtLocation(ast.NodeTransformer):
    def __init__(self,target_node_id,fragment):
        self.index=-1
        self.target_node_id=target_node_id
        self.fragment=fragment

    def visit_Name(self,node):
        if isinstance(node.ctx,ast.Load) and node.id=="x":
            self.index+=1
            if self.index==self.target_node_id:
                return ast.copy_location(
                    copy.deepcopy(self.fragment),node)
        return node


@dataclass(frozen=True)
class TransferOutcome:
    status: str
    program: str|None
    program_sha256: str|None
    library_origin_ids: tuple
    source_candidates_checked: int
    source_correct_max: int


def transfer_from_verified_sources(
        model_attempts,train,independent,library,runner,*,
        max_variants_per_program=32,exclude_origin_ids=()):
    """Produce new validated general code using only prior operator fragments.

    Inputs are SOURCE observations and earlier model-proposed code, never
    TARGET gold. Baseline may supply multiple failed candidate programs.
    Only verified prior-origin expression fragments can be composed.
    """
    if not library._verified:
        raise ValueError("prior source library must be independently checked")
    forbidden=set(str(x) for x in exclude_origin_ids)
    active=[
        op for op in library.records if op.origin_id not in forbidden
    ]
    if not active or not train or not independent:
        return TransferOutcome("ABSTAIN_NO_TRANSFER_SOURCE",None,None,(),0,0)
    # Fragment origins are certified independently of this new target.
    # Restrict to source-backed set visible before the new target.
    tree_fragments=tuple(
        ast.parse(f,mode="eval").body for f in library.fragments)
    attempts=sorted(
        (a for a in model_attempts
         if isinstance(a.program,str) and a.status in (
             "EXECUTED","EXECUTED_WITH_ERRORS")),
        key=lambda a:(-a.source_correct,a.iteration))
    seen=set()
    examined=0
    highest=0
    for attempt in attempts:
        try:
            baseline=validate_code(attempt.program)
        except UnsafeProposal:
            continue
        ast_base=ast.parse(baseline)
        count=sum(
            isinstance(x,ast.Name) and x.id=="x" and
            isinstance(x.ctx,ast.Load)
            for x in ast.walk(ast_base))
        variants=0
        for pattern in tree_fragments:
            for slot in range(count):
                if variants>=max_variants_per_program:break
                cloned=copy.deepcopy(ast_base)
                patched=_ReplaceAtLocation(
                    slot,pattern).visit(cloned)
                ast.fix_missing_locations(patched)
                src=ast.unparse(patched)
                if src==baseline or src in seen:
                    continue
                seen.add(src)
                try:
                    src=validate_code(src)
                except UnsafeProposal:
                    continue
                variants+=1
                examined+=1
                result=runner.evaluate(src,[a for a,b in train])
                if result.status!="EXECUTED":continue
                matched=sum(y==actual for (_,y),actual
                            in zip(train,result.outputs))
                highest=max(highest,matched)
                if matched!=len(train):continue
                independent_result=runner.evaluate(
                    src,[x for x,y in independent])
                if independent_result.status!="EXECUTED":continue
                if not all(result==y for result,(_,y)
                           in zip(independent_result.outputs,independent)):
                    continue
                return TransferOutcome(
                    "SOURCE_VERIFIED_TRANSFERRED_FRAGMENT",
                    src,_sha(src),
                    tuple(o.origin_id for o in active),
                    examined,highest)
    return TransferOutcome(
        "ABSTAIN_NO_NEW_SOURCE_CORRECT_TRANSFER",None,None,
        tuple(o.origin_id for o in active),examined,highest)
